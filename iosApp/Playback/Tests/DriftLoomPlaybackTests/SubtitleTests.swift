final class SubtitleParsingTests: XCTestCase {
    func testParsesYouTubeWebVTTWithSettingsTagsAndEntities() {
        let source = """
        WEBVTT
        Kind: captions
        Language: en

        1
        00:00:01.360 --> 00:00:03.040 align:start position:0%
        [<c.music>♪♪♪</c>]

        00:00:18.640 --> 00:00:21.880
        We&#39;re no <00:00:19.000><c>strangers</c>
        to &amp; love

        broken --> cue

        01:00:00.000 --> 01:00:02.500
        &lt;hour&gt;
        """
        let cues = WebVTT.parse(source)
        XCTAssertEqual(cues.count, 3)
        XCTAssertEqual(cues[0], SubtitleCue(start: 1.36, end: 3.04, text: "[♪♪♪]"))
        XCTAssertEqual(cues[1].text, "We're no strangers\nto & love")
        XCTAssertEqual(cues[1].start, 18.64, accuracy: 0.0001)
        XCTAssertEqual(cues[2].start, 3600)
        XCTAssertEqual(cues[2].text, "<hour>")
    }
    func testRejectsNonVTTAndInvalidTimings() {
        XCTAssertTrue(WebVTT.parse("<transcript></transcript>").isEmpty)
        XCTAssertTrue(WebVTT.parse("").isEmpty)
        XCTAssertTrue(WebVTT.parse("WEBVTT\r\n\r\n00:00:05.000 --> 00:00:04.000\r\nbackwards\r\n\r\n00:00:61.000 --> 00:01:02.000\r\nbad seconds").isEmpty)
        XCTAssertEqual(WebVTT.parse("\u{FEFF}WEBVTT\r\n\r\n00:01.000 --> 00:02.000\r\nshort form").first?.start, 1)
    }
    func testTimelineShowsOverlappingCuesAndGaps() {
        let timeline = SubtitleTimeline([
            SubtitleCue(start: 10, end: 20, text: "long"),
            SubtitleCue(start: 12, end: 14, text: "inner"),
            SubtitleCue(start: 30, end: 31, text: "later")
        ])
        XCTAssertNil(timeline.text(at: 9.99))
        XCTAssertEqual(timeline.text(at: 10), "long")
        XCTAssertEqual(timeline.text(at: 13), "long\ninner")
        XCTAssertEqual(timeline.text(at: 19.5), "long")
        XCTAssertNil(timeline.text(at: 20))
        XCTAssertEqual(timeline.text(at: 30.5), "later")
        XCTAssertNil(timeline.text(at: .nan))
        XCTAssertNil(SubtitleTimeline([]).text(at: 1))
    }
    func testSelectionPrefersUploaderTracksAndMatchesRegionalCodes() {
        let url = URL(string: "https://www.youtube.com/api/timedtext?v=x")!
        let auto = SubtitleTrack(languageCode: "en", name: "English (auto-generated)", isAutoGenerated: true, url: url)
        let manual = SubtitleTrack(languageCode: "en-GB", name: "English (United Kingdom)", isAutoGenerated: false, url: url)
        let german = SubtitleTrack(languageCode: "de-DE", name: "German", isAutoGenerated: false, url: url)
        XCTAssertEqual(SubtitleSelection.preferred([auto, manual, german], language: "en"), manual)
        XCTAssertEqual(SubtitleSelection.preferred([auto, german], language: "en"), auto)
        XCTAssertEqual(SubtitleSelection.preferred([auto, german], language: "de"), german)
        XCTAssertNil(SubtitleSelection.preferred([auto, german], language: "ja"))
        XCTAssertNil(SubtitleSelection.preferred([auto], language: nil))
        XCTAssertNotEqual(auto.id, SubtitleTrack(languageCode: "en", name: "English", isAutoGenerated: false, url: url).id)
    }
    func testPlayerResponseTracksRejectUntrustedHostsAndDuplicates() {
        let root: [String: Any] = ["captions": ["playerCaptionsTracklistRenderer": ["captionTracks": [
            ["baseUrl": "https://www.youtube.com/api/timedtext?v=a&lang=en", "languageCode": "en", "name": ["runs": [["text": "English"]]]],
            ["baseUrl": "https://www.youtube.com/api/timedtext?v=a&lang=en&kind=asr", "languageCode": "en", "kind": "asr", "name": ["simpleText": "English (auto-generated)"]],
            ["baseUrl": "https://www.youtube.com/api/timedtext?v=a&lang=en&dup", "languageCode": "en", "name": ["simpleText": "Duplicate"]],
            ["baseUrl": "https://youtube.com.evil.test/api/timedtext", "languageCode": "fr"],
            ["baseUrl": "http://www.youtube.com/api/timedtext", "languageCode": "es"],
            ["languageCode": "pt"]
        ]]]]
        let tracks = YouTubeSubtitleClient.tracks(in: root)
        XCTAssertEqual(tracks.map(\.id), ["en", "en.auto"])
        XCTAssertEqual(tracks.map(\.name), ["English", "English (auto-generated)"])
        XCTAssertTrue(YouTubeSubtitleClient.tracks(in: [:]).isEmpty)
    }
    func testSavedSubtitlesRoundTripWithoutSourceURLs() throws {
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString + ".subtitles.json")
        defer { try? FileManager.default.removeItem(at: url) }
        let track = SubtitleTrack(languageCode: "en", name: "English", isAutoGenerated: false,
                                  url: URL(string: "https://www.youtube.com/api/timedtext?signature=secret")!)
        try SubtitleFiles.save(track, cues: [SubtitleCue(start: 1, end: 2, text: "Hello")], to: url)
        XCTAssertFalse(try String(contentsOf: url, encoding: .utf8).contains("secret"))
        let loaded = try XCTUnwrap(SubtitleFiles.load(from: url))
        XCTAssertEqual(loaded.0.id, "en"); XCTAssertEqual(loaded.0.url, url); XCTAssertEqual(loaded.1.first?.text, "Hello")
        try Data("{\"version\":2}".utf8).write(to: url)
        XCTAssertNil(SubtitleFiles.load(from: url))
        XCTAssertThrowsError(try SubtitleFiles.save(track, cues: [], to: url))
    }
    @MainActor func testDownloadRecordsDecodeOlderJobsAndValidateSubtitlePaths() throws {
        let item = BrowseItem(contentID: "dQw4w9WgXcQ", kind: .video, title: "Video")
        var record = DownloadRecord(item: item, choice: DownloadChoice(id: "hls", name: "HLS", kind: .hls), subtitleLanguage: "en")
        let decoded = try JSONDecoder().decode(DownloadRecord.self, from: JSONEncoder().encode(record))
        XCTAssertEqual(decoded.subtitleLanguage, "en"); XCTAssertNil(decoded.subtitlePath)
        let file = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString + ".json")
        defer { try? FileManager.default.removeItem(at: file) }
        record.subtitlePath = "../escape.subtitles.json"
        let library = DownloadLibrary(fileURL: file)
        XCTAssertFalse(library.add(record))
        record.subtitlePath = "Library/Application Support/DriftLoom/Media/x.subtitles.json"
        XCTAssertTrue(library.add(record))
    }
}

private actor FakeSubtitles: SubtitleLoading {
    let available: [SubtitleTrack]
    private(set) var fetched: [String] = []
    init(_ tracks: [SubtitleTrack]) { available = tracks }
    func tracks(videoID: String) async throws -> [SubtitleTrack] { available }
    func cues(for track: SubtitleTrack) async throws -> [SubtitleCue] {
        fetched.append(track.id)
        if track.languageCode == "xx" { throw BrowseError.unavailable("broken") }
        return [SubtitleCue(start: 0, end: 3600, text: "Track " + track.id)]
    }
}

private struct NeverResolves: StreamResolving {
    func resolve(_ request: VideoRequest) async throws -> ResolvedVideo {
        try await Task.sleep(nanoseconds: 60_000_000_000); throw CancellationError()
    }
}

@MainActor
final class SubtitleSessionTests: XCTestCase {
    private let url = URL(string: "https://www.youtube.com/api/timedtext?v=x")!
    private func wait(_ condition: @escaping @MainActor () -> Bool) async {
        for _ in 0..<200 where !condition() { try? await Task.sleep(nanoseconds: 10_000_000) }
    }
    func testPreferredLanguageSelectsAutomaticallyAndChoicesAreReported() async {
        let tracks = [SubtitleTrack(languageCode: "en", name: "English", isAutoGenerated: false, url: url),
                      SubtitleTrack(languageCode: "de", name: "German", isAutoGenerated: false, url: url),
                      SubtitleTrack(languageCode: "xx", name: "Broken", isAutoGenerated: false, url: url)]
        let loader = FakeSubtitles(tracks)
        let session = PlaybackSession(resolver: NeverResolves(), subtitles: loader)
        var reported: [String?] = []
        session.onSubtitleChoice = { reported.append($0) }
        session.preferredSubtitleLanguage = "de"
        session.open("dQw4w9WgXcQ")
        await wait { session.selectedSubtitle?.id == "de" && session.subtitle(at: 1) != nil }
        XCTAssertEqual(session.subtitleTracks.count, 3)
        XCTAssertEqual(session.subtitle(at: 1), "Track de")
        XCTAssertTrue(reported.isEmpty, "Automatic selection must not rewrite the preference")

        session.selectSubtitle(tracks[2])
        await wait { session.subtitleError != nil }
        XCTAssertNil(session.subtitle(at: 1))
        XCTAssertEqual(reported, ["xx"])

        session.selectSubtitle(nil)
        XCTAssertNil(session.selectedSubtitle); XCTAssertNil(session.subtitle(at: 1)); XCTAssertNil(session.subtitleError)
        XCTAssertEqual(reported, ["xx", nil])
        XCTAssertNil(session.preferredSubtitleLanguage)

        session.stop()
        XCTAssertTrue(session.subtitleTracks.isEmpty)
    }
    func testNoPreferenceLeavesSubtitlesOffAndNewVideoClearsOldTracks() async {
        let loader = FakeSubtitles([SubtitleTrack(languageCode: "en", name: "English", isAutoGenerated: false, url: url)])
        let session = PlaybackSession(resolver: NeverResolves(), subtitles: loader)
        session.open("dQw4w9WgXcQ")
        await wait { !session.subtitleTracks.isEmpty }
        XCTAssertNil(session.selectedSubtitle)
        let fetched = await loader.fetched
        XCTAssertTrue(fetched.isEmpty)
        session.open("not a video")
        XCTAssertTrue(session.subtitleTracks.isEmpty)
    }
    func testDownloadedSubtitlesAreUsedWithoutTheNetwork() async {
        let loader = FakeSubtitles([])
        let session = PlaybackSession(resolver: NeverResolves(), subtitles: loader)
        let file = URL(fileURLWithPath: "/tmp/saved.subtitles.json")
        session.localSubtitles = { _ in (SubtitleTrack(languageCode: "en", name: "English", isAutoGenerated: false, url: file), [SubtitleCue(start: 0, end: 10, text: "Offline")]) }
        session.preferredSubtitleLanguage = "en"
        session.open("dQw4w9WgXcQ")
        XCTAssertEqual(session.selectedSubtitle?.url, file)
        XCTAssertEqual(session.subtitle(at: 1), "Offline")
        session.selectSubtitle(nil); session.selectSubtitle(session.subtitleTracks[0])
        XCTAssertEqual(session.subtitle(at: 1), "Offline")
        let fetched = await loader.fetched
        XCTAssertTrue(fetched.isEmpty)
    }
}

final class ExtractionErrorTests: XCTestCase {
    func testUndescribedExtractorErrorsBecomeReadable() {
        XCTAssertEqual(PlaybackError.readable(YouTubeKitError.extractError) as? PlaybackError, .extractionRefused)
        XCTAssertFalse(PlaybackError.extractionRefused.localizedDescription.contains("YouTubeKit"))
        XCTAssertEqual(PlaybackError.readable(YouTubeKitError.videoPrivate).localizedDescription, "Video is private")
        XCTAssertEqual(PlaybackError.readable(BrowseError.invalidInput).localizedDescription, BrowseError.invalidInput.localizedDescription)
    }
}

@MainActor
final class SubtitlePreferenceTests: XCTestCase {
    func testLanguageAndSizePersistAndInvalidValuesFallBack() {
        let name = "DriftLoom.Tests." + UUID().uuidString
        let defaults = UserDefaults(suiteName: name)!
        defer { defaults.removePersistentDomain(forName: name) }
        let preferences = AppPreferences(defaults: defaults)
        XCTAssertNil(preferences.subtitleLanguage); XCTAssertEqual(preferences.subtitleSize, .medium)
        preferences.setSubtitleLanguage("pt-BR"); preferences.setSubtitleSize(.large)
        let reloaded = AppPreferences(defaults: defaults)
        XCTAssertEqual(reloaded.subtitleLanguage, "pt"); XCTAssertEqual(reloaded.subtitleSize, .large)
        reloaded.setSubtitleLanguage(nil)
        XCTAssertNil(AppPreferences(defaults: defaults).subtitleLanguage)
        defaults.set("not-a-language", forKey: "subtitleLanguage"); defaults.set("Huge", forKey: "subtitleSize")
        XCTAssertNil(AppPreferences(defaults: defaults).subtitleLanguage)
        XCTAssertEqual(AppPreferences(defaults: defaults).subtitleSize, .medium)
    }
}
