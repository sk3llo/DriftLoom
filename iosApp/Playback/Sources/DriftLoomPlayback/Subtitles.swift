import Foundation

public struct SubtitleTrack: Codable, Hashable, Identifiable, Sendable {
    public let languageCode: String
    public let name: String
    public let isAutoGenerated: Bool
    public let url: URL
    /// Set when YouTube machine-translates this track into another language.
    public var translationCode: String?
    public var id: String { languageCode + (isAutoGenerated ? ".auto" : "") + (translationCode.map { ">" + $0 } ?? "") }
    /// The language the viewer actually reads.
    public var displayLanguage: String { translationCode ?? languageCode }
    public init(languageCode: String, name: String, isAutoGenerated: Bool, url: URL, translationCode: String? = nil) {
        self.languageCode = languageCode; self.name = name; self.isAutoGenerated = isAutoGenerated; self.url = url
        self.translationCode = translationCode
    }
    /// This track machine-translated by YouTube into `language`.
    public func translated(to language: SubtitleLanguage) -> SubtitleTrack {
        SubtitleTrack(languageCode: languageCode, name: language.name + " (auto-translated)", isAutoGenerated: isAutoGenerated,
                      url: url, translationCode: language.code)
    }
}

/// A target language YouTube can translate subtitles into.
public struct SubtitleLanguage: Hashable, Identifiable, Sendable {
    public let code: String
    public let name: String
    public var id: String { code }
    public init(code: String, name: String) { self.code = code; self.name = name }
}

/// Available tracks, translation targets, and the track YouTube recommends translating from.
public struct SubtitleCatalog: Sendable {
    public var tracks: [SubtitleTrack]
    public var translations: [SubtitleLanguage]
    public var translationSource: SubtitleTrack?
    public init(tracks: [SubtitleTrack], translations: [SubtitleLanguage] = [], translationSource: SubtitleTrack? = nil) {
        self.tracks = tracks; self.translations = translations; self.translationSource = translationSource
    }
    /// The preferred native track, else a translation of the source track into the language when allowed.
    public func preferred(language: String?, allowTranslation: Bool) -> SubtitleTrack? {
        if let native = SubtitleSelection.preferred(tracks, language: language) { return native }
        guard allowTranslation, let language, let source = translationSource,
              let target = translations.first(where: { SubtitleSelection.baseLanguage($0.code) == language }) else { return nil }
        return source.translated(to: target)
    }
}

public struct SubtitleCue: Codable, Equatable, Sendable {
    public let start: Double
    public let end: Double
    public let text: String
    public init(start: Double, end: Double, text: String) { self.start = start; self.end = end; self.text = text }
}

public enum SubtitleSize: String, CaseIterable, Identifiable, Sendable {
    case small = "Small", medium = "Medium", large = "Large"
    public var id: String { rawValue }
    public var scale: Double { self == .small ? 0.85 : self == .large ? 1.3 : 1 }
}

/// Parses the WebVTT subset YouTube serves: timing lines with optional settings, inline
/// voice/class/timestamp tags, and character references. Malformed blocks are skipped.
public enum WebVTT {
    public static let maximumCues = 20_000
    public static func parse(_ source: String) -> [SubtitleCue] {
        let normalized = source.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        guard normalized.hasPrefix("WEBVTT") || normalized.hasPrefix("\u{FEFF}WEBVTT") else { return [] }
        var cues: [SubtitleCue] = []
        for block in normalized.components(separatedBy: "\n\n") {
            guard cues.count < maximumCues else { break }
            let lines = block.split(separator: "\n", omittingEmptySubsequences: true).map(String.init)
            guard let timing = lines.firstIndex(where: { $0.contains("-->") }) else { continue }
            let parts = lines[timing].components(separatedBy: "-->")
            guard parts.count == 2, let start = timestamp(parts[0]),
                  let end = timestamp(parts[1].split(separator: " ", omittingEmptySubsequences: true).first.map(String.init) ?? ""),
                  end > start else { continue }
            let text = lines[(timing + 1)...].map(clean).filter { !$0.isEmpty }.joined(separator: "\n")
            if !text.isEmpty { cues.append(SubtitleCue(start: start, end: end, text: text)) }
        }
        return cues.sorted { $0.start < $1.start }
    }
    static func timestamp(_ raw: String) -> Double? {
        let fields = raw.trimmingCharacters(in: .whitespaces).split(separator: ":")
        guard (2...3).contains(fields.count), let seconds = Double(fields.last!), seconds >= 0, seconds < 60 else { return nil }
        var total = seconds, multiplier = 60.0
        for field in fields.dropLast().reversed() {
            guard let value = Int(field), value >= 0 else { return nil }
            total += Double(value) * multiplier; multiplier *= 60
        }
        return total
    }
    static func clean(_ line: String) -> String {
        var text = line.replacingOccurrences(of: "<[^>]*>", with: "", options: .regularExpression)
        for (entity, value) in [("&lt;", "<"), ("&gt;", ">"), ("&nbsp;", " "), ("&lrm;", ""), ("&rlm;", ""), ("&#39;", "'"), ("&quot;", "\""), ("&amp;", "&")] {
            text = text.replacingOccurrences(of: entity, with: value)
        }
        return text.trimmingCharacters(in: .whitespaces)
    }
}

/// Looks up the visible cue text for a playback time. Overlapping cues are shown together.
public struct SubtitleTimeline: Sendable {
    public let cues: [SubtitleCue]
    private let longest: Double
    public init(_ cues: [SubtitleCue]) {
        self.cues = cues.sorted { $0.start < $1.start }
        longest = cues.map { $0.end - $0.start }.max() ?? 0
    }
    public func text(at time: Double) -> String? {
        guard time.isFinite else { return nil }
        var low = 0, high = cues.count
        while low < high { let mid = (low + high) / 2; if cues[mid].start <= time { low = mid + 1 } else { high = mid } }
        var visible: [String] = []
        var index = low - 1
        while index >= 0, cues[index].start >= time - longest {
            if cues[index].end > time { visible.insert(cues[index].text, at: 0) }
            index -= 1
        }
        return visible.isEmpty ? nil : visible.joined(separator: "\n")
    }
}

public enum SubtitleSelection {
    /// Prefer a manually authored track in the language, then an automatic one.
    public static func preferred(_ tracks: [SubtitleTrack], language: String?) -> SubtitleTrack? {
        guard let language, !language.isEmpty else { return nil }
        func matches(_ track: SubtitleTrack) -> Bool {
            track.languageCode == language || track.languageCode.split(separator: "-").first.map(String.init) == language
        }
        return tracks.first { matches($0) && !$0.isAutoGenerated } ?? tracks.first { matches($0) }
    }
    public static func baseLanguage(_ code: String) -> String { code.split(separator: "-").first.map(String.init) ?? code }
}

public protocol SubtitleLoading: Sendable {
    func tracks(videoID: String) async throws -> [SubtitleTrack]
    func catalog(videoID: String) async throws -> SubtitleCatalog
    func cues(for track: SubtitleTrack) async throws -> [SubtitleCue]
    /// Seek-bar preview frames, from the same player response as the captions.
    func storyboard(videoID: String) async -> Storyboard?
}

public extension SubtitleLoading {
    func catalog(videoID: String) async throws -> SubtitleCatalog { SubtitleCatalog(tracks: try await tracks(videoID: videoID)) }
    func storyboard(videoID: String) async -> Storyboard? { nil }
}

/// Lists YouTube caption tracks through the iOS InnerTube client. Web player caption URLs
/// require a proof-of-origin token and return empty bodies without one.
public actor YouTubeSubtitleClient: SubtitleLoading {
    static let clientVersion = "20.10.4"
    private let session: URLSession
    /// The last player response, so captions and storyboards for one video cost one request.
    private var cached: (videoID: String, root: [String: Any], date: Date)?
    public init(session: URLSession? = nil) {
        let configuration = URLSessionConfiguration.ephemeral
        configuration.httpCookieStorage = nil; configuration.urlCache = nil
        configuration.timeoutIntervalForRequest = 20
        self.session = session ?? URLSession(configuration: configuration)
    }
    public func tracks(videoID: String) async throws -> [SubtitleTrack] { try await catalog(videoID: videoID).tracks }
    public func catalog(videoID: String) async throws -> SubtitleCatalog { Self.catalog(in: try await playerResponse(videoID)) }
    public func storyboard(videoID: String) async -> Storyboard? {
        guard let root = try? await playerResponse(videoID),
              let spec = ((root["storyboards"] as? [String: Any])?["playerStoryboardSpecRenderer"] as? [String: Any])?["spec"] as? String,
              spec.count <= 20_000 else { return nil }
        return Storyboard(spec: spec)
    }
    private func playerResponse(_ videoID: String) async throws -> [String: Any] {
        if let cached, cached.videoID == videoID, Date().timeIntervalSince(cached.date) < 600 { return cached.root }
        guard (try? VideoRequest(input: videoID).videoID) == videoID, !SoundCloudID.isSoundCloud(videoID) else { throw BrowseError.invalidInput }
        let locale = ContentLocale.current()
        var request = URLRequest(url: URL(string: "https://www.youtube.com/youtubei/v1/player?prettyPrint=false")!)
        request.httpMethod = "POST"
        request.setValue("application/json", forHTTPHeaderField: "Content-Type")
        request.setValue("com.google.ios.youtube/\(Self.clientVersion) (iPhone16,2; U; CPU iOS 18_3_2 like Mac OS X)", forHTTPHeaderField: "User-Agent")
        request.httpBody = try JSONSerialization.data(withJSONObject: [
            "context": ["client": ["clientName": "IOS", "clientVersion": Self.clientVersion, "deviceMake": "Apple",
                                   "deviceModel": "iPhone16,2", "osName": "iPhone", "osVersion": "18.3.2.22D82",
                                   "hl": locale.language, "gl": locale.country]],
            "videoId": videoID
        ])
        let data = try await fetch(request, limit: 4_000_000)
        guard let root = try JSONSerialization.jsonObject(with: data) as? [String: Any] else { throw BrowseError.unsupportedResponse }
        cached = (videoID, root, Date())
        return root
    }
    public func cues(for track: SubtitleTrack) async throws -> [SubtitleCue] {
        guard let url = Self.webVTTURL(for: track) else { throw BrowseError.unsupportedResponse }
        let data = try await fetch(URLRequest(url: url), limit: 6_000_000)
        guard let text = String(data: data, encoding: .utf8) else { throw BrowseError.unsupportedResponse }
        let cues = WebVTT.parse(text)
        guard !cues.isEmpty else { throw BrowseError.unavailable(L("These subtitles are empty or couldn't be read.")) }
        return cues
    }
    /// The track's caption URL asking for WebVTT, plus a translation target when set.
    static func webVTTURL(for track: SubtitleTrack) -> URL? {
        guard trusted(track.url), var components = URLComponents(url: track.url, resolvingAgainstBaseURL: false) else { return nil }
        components.queryItems = (components.queryItems ?? []).filter { $0.name != "fmt" && $0.name != "tlang" } + [URLQueryItem(name: "fmt", value: "vtt")]
            + (track.translationCode.map { [URLQueryItem(name: "tlang", value: $0)] } ?? [])
        return components.url
    }
    static func trusted(_ url: URL) -> Bool {
        guard url.scheme == "https", let host = url.host?.lowercased() else { return false }
        return host == "www.youtube.com" || host == "youtube.com" || host.hasSuffix(".youtube.com")
    }
    static func catalog(in root: [String: Any]) -> SubtitleCatalog {
        let renderer = (root["captions"] as? [String: Any])?["playerCaptionsTracklistRenderer"] as? [String: Any]
        let raw = renderer?["captionTracks"] as? [[String: Any]] ?? []
        let tracks = tracks(in: root)
        var seen = Set<String>()
        let translations = (renderer?["translationLanguages"] as? [[String: Any]] ?? []).compactMap { entry -> SubtitleLanguage? in
            guard let code = entry["languageCode"] as? String, code.range(of: "^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})?$", options: .regularExpression) != nil,
                  seen.insert(code).inserted else { return nil }
            let name = DiscussionParser.text(entry["languageName"])
            return SubtitleLanguage(code: code, name: name.isEmpty ? code : name)
        }.prefix(300)
        // Prefer the track YouTube names as the translation source, else an uploaded translatable track.
        let indices = renderer?["defaultTranslationSourceTrackIndices"] as? [Int] ?? []
        let translatable = raw.enumerated().filter { $0.element["isTranslatable"] as? Bool == true }.map(\.offset)
        let sourceIndex = indices.first(where: translatable.contains)
            ?? translatable.first(where: { raw[$0]["kind"] as? String != "asr" }) ?? translatable.first
        let source = sourceIndex.flatMap { index -> SubtitleTrack? in
            guard let code = raw[index]["languageCode"] as? String else { return nil }
            let automatic = raw[index]["kind"] as? String == "asr"
            return tracks.first { $0.languageCode == code && $0.isAutoGenerated == automatic }
        }
        return SubtitleCatalog(tracks: tracks, translations: source == nil ? [] : Array(translations), translationSource: source)
    }
    static func tracks(in root: [String: Any]) -> [SubtitleTrack] {
        let renderer = (root["captions"] as? [String: Any])?["playerCaptionsTracklistRenderer"] as? [String: Any]
        var seen = Set<String>()
        return (renderer?["captionTracks"] as? [[String: Any]] ?? []).compactMap { track in
            guard let code = track["languageCode"] as? String, !code.isEmpty, code.count <= 20,
                  let raw = track["baseUrl"] as? String, let url = URL(string: raw), trusted(url) else { return nil }
            let automatic = track["kind"] as? String == "asr"
            let name = DiscussionParser.text(track["name"])
            let value = SubtitleTrack(languageCode: code, name: name.isEmpty ? code : name, isAutoGenerated: automatic, url: url)
            return seen.insert(value.id).inserted ? value : nil
        }
    }
    private func fetch(_ request: URLRequest, limit: Int) async throws -> Data {
        let (data, response) = try await session.data(for: request)
        try Task.checkCancellation()
        guard let http = response as? HTTPURLResponse, let url = http.url, Self.trusted(url), data.count < limit else {
            throw BrowseError.unsupportedResponse
        }
        if http.statusCode == 429 {
            throw BrowseError.unavailable(L("YouTube is limiting subtitle requests from this network right now, which affects auto-translated subtitles most. Try again later or choose another track."))
        }
        guard http.statusCode == 200 else { throw BrowseError.unavailable(L("YouTube couldn't load subtitles (\(http.statusCode)).")) }
        return data
    }
}

/// Subtitles saved next to a download. Only cue text and track labels are stored, never the signed source URL.
public enum SubtitleFiles {
    private struct Document: Codable { var version = 1; var languageCode: String; var name: String; var isAutoGenerated: Bool; var translationCode: String? = nil; var cues: [SubtitleCue] }
    public static func save(_ track: SubtitleTrack, cues: [SubtitleCue], to url: URL) throws {
        guard !cues.isEmpty, cues.count <= WebVTT.maximumCues else { throw CocoaError(.fileWriteUnknown) }
        let data = try JSONEncoder().encode(Document(languageCode: track.languageCode, name: track.name, isAutoGenerated: track.isAutoGenerated,
                                                     translationCode: track.translationCode, cues: cues))
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        var options: Data.WritingOptions = .atomic
#if os(iOS)
        options.insert(.completeFileProtectionUntilFirstUserAuthentication)
#endif
        try data.write(to: url, options: options)
    }
    public static func load(from url: URL) -> (SubtitleTrack, [SubtitleCue])? {
        guard let data = try? Data(contentsOf: url), data.count < 12_000_000,
              let document = try? JSONDecoder().decode(Document.self, from: data), document.version == 1,
              !document.cues.isEmpty, document.cues.count <= WebVTT.maximumCues, document.languageCode.count <= 20, (document.translationCode?.count ?? 0) <= 20,
              document.cues.allSatisfy({ $0.start.isFinite && $0.end.isFinite && $0.end > $0.start }) else { return nil }
        return (SubtitleTrack(languageCode: document.languageCode, name: document.name, isAutoGenerated: document.isAutoGenerated, url: url,
                              translationCode: document.translationCode), document.cues)
    }
}
